CREATE DATABASE IF NOT EXISTS $DATABASE;
CREATE USER '$USERNAME'@'$HOSTNAME' IDENTIFIED BY '$PASSWORD';
GRANT ALL ON `$DATABASE`.* TO '$USERNAME'@'$HOSTNAME';

-- Read-Only Export Database User
CREATE USER '$EXPORT_USERNAME'@'$HOSTNAME' IDENTIFIED BY '$EXPORT_PASSWORD';
GRANT SELECT ON `$DATABASE`.* TO '$EXPORT_USERNAME'@'$HOSTNAME';
flush privileges;