    private void openUrl(URI uri) {
        if (Desktop.isDesktopSupported()) {
            try {
                Desktop.getDesktop().browse(uri);
            } catch (IOException ex) {
                Logger.getLogger(PanelGoodbye.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }
    
